<?php

namespace Aotr\AnimatedIcons\Actions;

use Illuminate\Support\Facades\Http;
use RuntimeException;

/**
 * Fetches an AnimateIcons registry icon and writes it into the generated icon
 * config. Hand-authored icons live in the host app's config and are never
 * touched. Writes are locked and atomic (temp file + rename).
 */
class SyncAnimatedIconAction
{
    public function __construct(private ConvertAnimatedIconSourceAction $convert) {}

    /**
     * @return array{name: string, parts: int, entry: array{markup: string, animation: array<string, mixed>}, path: string|null}
     */
    public function handle(string $name, bool $write = true, ?string $path = null): array
    {
        $name = $this->normalizeName($name);
        $path = $path ?? (string) config('animated-icons.generated_path', config_path('animated-icons-generated.php'));

        $entry = $this->convert->handle($this->fetch($name));

        if ($write) {
            $this->writeEntry($path, $name, $entry);
        }

        return [
            'name' => $name,
            'parts' => count($entry['animation']),
            'entry' => $entry,
            'path' => $write ? $path : null,
        ];
    }

    /**
     * @param  array{markup: string, animation: array<string, mixed>}  $entry
     */
    public function renderEntry(string $name, array $entry): string
    {
        $lines = ["    '{$name}' => ["];
        $lines[] = "        'markup' => ".$this->exportScalar($entry['markup']).',';
        $lines[] = "        'animation' => ".$this->exportParts($entry['animation'], 2).',';
        $lines[] = '    ],';

        return implode("\n", $lines);
    }

    /**
     * @param  array<string, array{markup: string, animation: array<string, mixed>}>  $icons
     */
    public function renderFile(array $icons): string
    {
        $header = "<?php\n\n// Generated by `php artisan animateicons:sync` — do not edit by hand.\n\n";

        if ($icons === []) {
            return $header."return [];\n";
        }

        $blocks = [];

        foreach ($icons as $name => $icon) {
            $blocks[] = $this->renderEntry($name, $icon);
        }

        return $header."return [\n\n".implode("\n\n", $blocks)."\n\n];\n";
    }

    private function normalizeName(string $name): string
    {
        $name = strtolower(trim($name));
        $name = str_starts_with($name, 'lu-') ? substr($name, 3) : $name;

        if (preg_match('/^[a-z0-9]+(?:-[a-z0-9]+)*$/', $name) !== 1) {
            throw new RuntimeException("Invalid icon name [{$name}].");
        }

        return $name;
    }

    private function fetch(string $name): string
    {
        $response = Http::timeout(20)
            ->acceptJson()
            ->get("https://animateicons.in/r/lu-{$name}.json");

        if ($response->failed()) {
            throw new RuntimeException("The registry has no icon [lu-{$name}] (HTTP {$response->status()}).");
        }

        $source = $response->json('files.0.content');

        if (! is_string($source) || trim($source) === '') {
            throw new RuntimeException("The registry returned no source for [lu-{$name}].");
        }

        return $source;
    }

    /**
     * @param  array{markup: string, animation: array<string, mixed>}  $entry
     */
    private function writeEntry(string $path, string $name, array $entry): void
    {
        $lockPath = storage_path('framework/cache/animated-icons.lock');
        $lock = fopen($lockPath, 'c');

        if ($lock === false) {
            throw new RuntimeException("Could not open the icon lock file [{$lockPath}].");
        }

        try {
            if (! flock($lock, LOCK_EX)) {
                throw new RuntimeException('Could not lock the generated icon config.');
            }

            $icons = [];

            if (is_file($path)) {
                $loaded = require $path;

                if (! is_array($loaded)) {
                    throw new RuntimeException("Generated icon config [{$path}] did not return an array.");
                }

                /** @var array<string, array{markup: string, animation: array<string, mixed>}> $icons */
                $icons = $loaded;
            }

            $icons[$name] = $entry;

            $temporary = $path.'.tmp';

            if (file_put_contents($temporary, $this->renderFile($icons), LOCK_EX) === false) {
                throw new RuntimeException("Could not write [{$temporary}].");
            }

            if (! rename($temporary, $path)) {
                @unlink($temporary);

                throw new RuntimeException("Could not replace [{$path}].");
            }
        } finally {
            flock($lock, LOCK_UN);
            fclose($lock);
        }
    }

    /**
     * @param  array<string, mixed>  $animation
     */
    private function exportParts(array $animation, int $level): string
    {
        $indent = str_repeat('    ', $level);
        $childIndent = str_repeat('    ', $level + 1);
        $lines = ['['];

        foreach ($animation as $part => $spec) {
            $key = $this->exportScalar($part);

            if (is_array($spec) && array_is_list($spec)) {
                $lines[] = $childIndent.$key.' => '.$this->exportTrackList($spec, $level + 1).',';
            } elseif (is_array($spec)) {
                $lines[] = $childIndent.$key.' => '.$this->exportTrack($spec, $level + 1).',';
            }
        }

        $lines[] = $indent.']';

        return implode("\n", $lines);
    }

    /**
     * @param  list<array<string, mixed>>  $tracks
     */
    private function exportTrackList(array $tracks, int $level): string
    {
        $itemIndent = str_repeat('    ', $level + 1);
        $lines = ['['];

        foreach ($tracks as $track) {
            $lines[] = $itemIndent.$this->exportTrack($track, $level + 1).',';
        }

        $lines[] = str_repeat('    ', $level).']';

        return implode("\n", $lines);
    }

    /**
     * @param  array<string, mixed>  $track
     */
    private function exportTrack(array $track, int $level): string
    {
        $indent = str_repeat('    ', $level);
        $childIndent = str_repeat('    ', $level + 1);
        $lines = ['['];
        $lines[] = $childIndent."'keyframes' => ".$this->exportKeyframes((array) $track['keyframes'], $level + 1).',';
        $lines[] = $childIndent."'duration' => ".$this->exportScalar($track['duration']).',';
        $lines[] = $childIndent."'easing' => ".$this->exportScalar($track['easing']).',';

        if (array_key_exists('delay', $track)) {
            $lines[] = $childIndent."'delay' => ".$this->exportScalar($track['delay']).',';
        }

        $lines[] = $indent.']';

        return implode("\n", $lines);
    }

    /**
     * @param  array<int|string, mixed>  $keyframes
     */
    private function exportKeyframes(array $keyframes, int $level): string
    {
        $itemIndent = str_repeat('    ', $level + 1);
        $lines = ['['];

        foreach ($keyframes as $keyframe) {
            if (! is_array($keyframe)) {
                continue;
            }

            $pairs = [];

            foreach ($keyframe as $key => $value) {
                $pairs[] = $this->exportScalar($key).' => '.$this->exportScalar($value);
            }

            $lines[] = $itemIndent.'['.implode(', ', $pairs).'],';
        }

        $lines[] = str_repeat('    ', $level).']';

        return implode("\n", $lines);
    }

    private function exportScalar(mixed $value): string
    {
        if (is_string($value)) {
            return "'".str_replace(['\\', "'"], ['\\\\', "\\'"], $value)."'";
        }

        if (is_int($value)) {
            return (string) $value;
        }

        if (is_float($value)) {
            $formatted = rtrim(rtrim(number_format($value, 4, '.', ''), '0'), '.');

            return $formatted === '' || $formatted === '-0' ? '0' : $formatted;
        }

        if (is_bool($value)) {
            return $value ? 'true' : 'false';
        }

        if ($value === null) {
            return 'null';
        }

        throw new RuntimeException('Unsupported config value.');
    }
}
